DENS_SUS = 7800.0   # kg/m3 SUS201 (오스테나이트 가성비)
DENS_STK = 7850.0   # kg/m3 STK400 carbon

def plate_kg(area_m2, t_mm, dens=DENS_SUS):
    return area_m2 * (t_mm/1000.0) * dens

def pipe_kg_per_m(sec, t):   # square hollow section
    a = (sec*sec - (sec-2*t)**2)/1e6  # m2
    return a * DENS_STK

def solidbar_kg_per_m(sec):
    return (sec*sec/1e6)*DENS_STK

